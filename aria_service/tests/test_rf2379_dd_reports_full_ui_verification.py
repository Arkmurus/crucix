def test_server_mjs_catchall_proxy_has_auth():
    """The catch-all proxy must have requireAuth middleware.

    The catch-all is registered as:
      app.use('/api/aria', requireAuth, async (req, res, next) => { ... });
    The requireAuth is the second argument.
    """
    text = _read_server()
    # Find the catch-all proxy registration — look for app.use('/api/aria', requireAuth, ...
    # There are TWO app.use('/api/aria' calls: one is a comment about the multipart
    # pass-through, the other is the actual catch-all with requireAuth.
    idx = text.find("app.use('/api/aria', requireAuth")
    assert idx >= 0, (
        "Could not find app.use('/api/aria', requireAuth in server.mjs. "
        "The catch-all proxy must have requireAuth middleware."
    )
    # Verify it's the actual catch-all (not a comment)
    snippet = text[idx:idx+200]
    assert "requireAuth" in snippet, (
        f"Catch-all proxy missing requireAuth middleware. Snippet: {snippet[:200]}"
    )


