# ── helpers ──────────────────────────────────────────────────────────────

def _read(path: str) -> str:
    return (PUBLIC_DIR / path).read_text(encoding="utf-8", errors="replace")


def _read_server() -> str:
    return SERVER_MJS.read_text(encoding="utf-8", errors="replace")


def _extract_api_calls(text: str) -> set[str]:
    """Extract /api/... endpoint paths from JS/HTML source."""
    endpoints: set[str] = set()
    for m in re.finditer(r"""['"](/api/[a-zA-Z0-9_/.?=&-]+)['"]""", text):
        path = m.group(1).split("?")[0].rstrip("/")
        path = re.sub(r"/:[a-zA-Z_]+", "/:param", path)
        endpoints.add(path)
    return endpoints


def _extract_server_routes(text: str) -> set[str]:
    """Extract registered routes from server.mjs."""
    routes: set[str] = set()
    for m in re.finditer(
        r"""app\.(?:get|post|put|delete|use)\(['"](/api/[^'"]+)['"]""",
        text,
    ):
        path = m.group(1).rstrip("/")
        routes.add(path)
    for m in re.finditer(
        r"""ariaProxy\([^,]+,\s*[^,]+,\s*(['"`])(/api/[^'"`]+)\1""",
        text,
    ):
        path = m.group(2)
        path = re.sub(r'\$\{[^}]+\}', ':param', path).rstrip("/")
        routes.add(path)
    return routes


def _find_buttons(text: str) -> list[dict]:
    """Find all <button> elements and their attributes."""
    buttons = []
    for m in re.finditer(r'<button\s+([^>]*)>', text):
        attrs = m.group(1)
        btn = {
            "id": re.search(r'id="([^"]*)"', attrs),
            "class": re.search(r'class="([^"]*)"', attrs),
            "onclick": re.search(r'onclick="([^"]*)"', attrs),
            "data_action": re.search(r'data-action="([^"]*)"', attrs),
            "inner": "",
        }
        # Get inner text
        tag_end = m.end()
        close = text.find("</button>", tag_end)
        if close > 0:
            inner = text[tag_end:close]
            btn["inner"] = re.sub(r'<[^>]+>', '', inner).strip()[:80]
        buttons.append(btn)
    return buttons


def _find_data_actions(text: str) -> set[str]:
    return set(re.findall(r'data-action="([^"]*)"', text))


def _find_onclicks(text: str) -> set[str]:
    return set(re.findall(r'onclick="([^"]*)"', text))


def _find_event_listeners(text: str) -> set[str]:
    return set(re.findall(r'\.addEventListener\([\'"]([^\'"]+)[\'"]', text))


def _find_ids(text: str) -> set[str]:
    return set(re.findall(r'id="([^"]*)"', text))


