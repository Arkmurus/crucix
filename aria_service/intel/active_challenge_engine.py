# =============================================================================
# ACTIVE CHALLENGE ENGINE
# =============================================================================

class ARIAActiveChallengeEngine:
    """
    ARIA's active challenge capability.

    Transforms ARIA from a passive listener to an active analytical participant
    in meetings and deal conversations.

    Three modes:
    1. LIVE — processes meeting captions in real time, posts immediate challenges
    2. POST-MEETING — processes full transcript, surfaces deferred challenges
    3. WEEKLY — runs assumption audit across all active deals

    All challenges are internal-only (Tier 1 autonomy).
    No external sends. No client-facing outputs without human review.
    """

    RELEVANCE_THRESHOLD = 0.65   # Only post if relevance >= this
    MAX_CHALLENGES_PER_SEGMENT = 2  # Don't flood the channel

    # Patterns that indicate consensus forming — trigger devil's advocate
    CONSENSUS_PATTERNS = [
        r"\bwe(?:'re| are) (?:all )?(?:agreed|aligned|moving forward)\b",
        r"\blet'?s (?:proceed|go ahead|move forward|do this)\b",
        r"\beveryone(?:'s| is) (?:happy|comfortable|on board)\b",
        r"\bno (?:concerns|objections|issues)\b",
        r"\bwe(?:'ve| have) (?:decided|agreed|confirmed)\b",
        r"\bsounds? good\b.*\blet'?s\b",
        r"\bwe(?:'re| are) (?:good to go|ready to proceed)\b",
        r"\bi think we(?:'re| are) (?:done|there|sorted)\b",
    ]

    def __init__(self, deliver_fn=None):
        """
        Args:
            deliver_fn: Function that posts a challenge to the appropriate channel.
                        Signature: deliver_fn(challenge: Challenge, channel: str)
        """
        self.client = anthropic.Anthropic(api_key=config.anthropic_api_key)
        self.deliver = deliver_fn
        self._segment_buffer: list[str] = []
        self._challenges_this_meeting: list[Challenge] = []

    # ── LIVE MEETING MODE ─────────────────────────────────────────────────────

    def process_caption_segment(
        self,
        text: str,
        deal_context: DealContext,
        channel: str = "zoom_chat",
    ) -> list[Challenge]:
        """
        Process a segment of live meeting captions.
        Call this every 60-90 seconds with the latest caption text.

        Args:
            text:         New caption text since last call
            deal_context: Current deal context
            channel:      Where to post challenges

        Returns:
            List of challenges generated (may be empty)
        """
        if not text.strip():
            return []

        self._segment_buffer.append(text)
        # Analyse when buffer has accumulated ~300 words or consensus detected
        buffer_text = " ".join(self._segment_buffer)
        word_count = len(buffer_text.split())

        consensus_detected = any(
            re.search(pattern, buffer_text, re.IGNORECASE)
            for pattern in self.CONSENSUS_PATTERNS
        )

        if word_count < 150 and not consensus_detected:
            return []  # Not enough context yet

        # Generate challenges
        challenges = self._generate_challenges(buffer_text, deal_context)

        # Filter by relevance
        challenges = [c for c in challenges
                      if c.relevance_score >= self.RELEVANCE_THRESHOLD]

        # Limit volume
        immediate = [c for c in challenges
                     if c.urgency == ChallengeUrgency.IMMEDIATE]
        immediate = immediate[:self.MAX_CHALLENGES_PER_SEGMENT]

        # Deliver immediate challenges
        if self.deliver:
            for challenge in immediate:
                self.deliver(challenge, channel)

        self._challenges_this_meeting.extend(challenges)
        self._segment_buffer = []  # Reset buffer
        return challenges

    def end_of_meeting_summary(self, deal_context: DealContext) -> str:
        """
        Generate end-of-meeting challenge summary.
        Includes deferred challenges and unanswered DD gaps.
        """
        deferred = [c for c in self._challenges_this_meeting
                    if c.urgency == ChallengeUrgency.DEFERRED]
        dd_gaps = self._check_dd_gaps(
            asked_questions=[],  # Pass questions extracted from transcript
            deal_type=deal_context.deal_type,
        )

        lines = [
            "═" * 50,
            "ARIA — END OF MEETING CHALLENGE SUMMARY",
            f"Deal: {deal_context.deal_name}",
            f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}",
            "═" * 50,
        ]

        if deferred:
            lines += ["", f"DEFERRED CHALLENGES ({len(deferred)}):"]
            for i, c in enumerate(deferred, 1):
                lines.append(f"\n{i}. [{c.challenge_type.value}]")
                lines.append(f"   {c.text}")
                if c.recommended_action:
                    lines.append(f"   → {c.recommended_action}")

        if dd_gaps:
            lines += ["", f"DD GAPS — QUESTIONS NOT ASKED ({len(dd_gaps)}):"]
            for gap in dd_gaps[:5]:
                lines.append(f"  ⚠ {gap}")

        # Reset for next meeting
        self._challenges_this_meeting = []

        lines.append("\n" + "═" * 50)
        return "\n".join(lines)

    # ── DD GAP DETECTION ─────────────────────────────────────────────────────

    def check_dd_gaps(
        self,
        conversation_text: str,
        deal_type: str,
        deal_context: Optional[DealContext] = None,
    ) -> list[Challenge]:
        """
        Check which standard DD questions have not been asked.

        Args:
            conversation_text: Full conversation text to check against
            deal_type:        broker | oem | end_user | g2g
            deal_context:     Optional deal context for enhanced checking

        Returns:
            List of DD gap challenges
        """
        checklist = DD_CHECKLISTS.get(deal_type, DD_CHECKLISTS["broker"])
        text_lower = conversation_text.lower()
        gaps = []

        for question in checklist:
            # Check if the substance of this question has been addressed
            # Extract key terms from the question for keyword matching
            key_terms = self._extract_key_terms(question)
            addressed = sum(1 for term in key_terms if term in text_lower)

            if addressed < len(key_terms) * 0.5:  # Less than half the terms present
                gaps.append(question)

        if not gaps:
            return []

        challenges = []
        # Group gaps into a single challenge if there are many
        if len(gaps) >= 3:
            challenge = Challenge(
                challenge_type=ChallengeType.DD_GAP,
                urgency=ChallengeUrgency.IMMEDIATE,
                text=(
                    f"{len(gaps)} standard DD questions for a {deal_type} arrangement "
                    f"have not been addressed in this conversation:\n\n"
                    + "\n".join(f"  • {g}" for g in gaps[:5])
                    + (f"\n  ... and {len(gaps)-5} more." if len(gaps) > 5 else "")
                ),
                relevance_score=0.85,
                recommended_action=(
                    f"Address the critical items before proceeding. "
                    f"ARIA can draft the questions if needed."
                ),
                evidence=gaps[:3],
            )
            challenges.append(challenge)
        else:
            for gap in gaps:
                challenges.append(Challenge(
                    challenge_type=ChallengeType.DD_GAP,
                    urgency=ChallengeUrgency.DEFERRED,
                    text=f"This question was not asked: {gap}",
                    relevance_score=0.75,
                    recommended_action="Ask before next meeting or counterparty contact.",
                ))

        return challenges

    # ── ASSUMPTION AUDITOR ────────────────────────────────────────────────────

    def audit_assumptions(
        self,
        conversation_text: str,
        deal_context: DealContext,
    ) -> list[Challenge]:
        """
        Extract and surface unstated assumptions in the conversation.

        Uses both pattern matching (fast) and LLM analysis (thorough).
        """
        challenges = []
        text_lower = conversation_text.lower()
        stage = deal_context.stage or "qualification"

        # Check standard unstated assumptions for this deal stage
        stage_assumptions = COMMON_UNSTATED_ASSUMPTIONS.get(stage, [])
        for assumption in stage_assumptions:
            # Check if this assumption has been explicitly validated in the conversation
            key_terms = self._extract_key_terms(assumption)
            tested = any(term in text_lower for term in key_terms[:2])

            if not tested:
                challenges.append(Challenge(
                    challenge_type=ChallengeType.ASSUMPTION,
                    urgency=ChallengeUrgency.WEEKLY,
                    text=f"Unstated assumption detected: '{assumption}'",
                    relevance_score=0.70,
                    recommended_action=(
                        "Explicitly verify this assumption before the next deal stage decision."
                    ),
                ))

        # LLM-based assumption extraction for novel assumptions
        llm_assumptions = self._extract_assumptions_llm(
            conversation_text, deal_context
        )
        challenges.extend(llm_assumptions)

        return challenges

    # ── CORE CHALLENGE GENERATION (LLM) ──────────────────────────────────────

    def _generate_challenges(
        self,
        text: str,
        deal_context: DealContext,
    ) -> list[Challenge]:
        """
        Use Claude to generate specific, relevant challenges for the conversation.
        """
        system_prompt = f"""You are ARIA, an analytical AI team member at Arkmurus Group, 
a defence and security advisory firm. Your role in this meeting is to be the devil's advocate 
— to catch what the team might miss, challenge assumptions, and flag risks.

Current deal context:
  Deal: {deal_context.deal_name}
  Type: {deal_context.deal_type}
  Stage: {deal_context.stage}
  Counterparty: {deal_context.counterparty_name} ({deal_context.counterparty_country})
  Value: USD {deal_context.programme_value_usd:,.0f}
  Known risks: {', '.join(deal_context.known_risks[:3]) or 'none logged'}
  Prior claims by counterparty: {len(deal_context.prior_claims)} on record

RULES:
- Generate only challenges that are SPECIFIC to what was just said
- Do not generate generic risk warnings
- Each challenge must cite the specific statement that triggered it
- Score relevance 0.0-1.0 (only generate if you would score >= 0.65)
- Post type: internal team channel only — be direct, not diplomatic
- Maximum 3 challenges per response
- If nothing genuinely needs challenging, return empty array

Respond ONLY with JSON array. Example:
[
  {{
    "type": "DEVIL_ADVOCATE",
    "urgency": "IMMEDIATE",
    "text": "Specific challenge text here",
    "relevance_score": 0.85,
    "trigger_statement": "The exact statement that triggered this",
    "evidence": ["Supporting fact 1", "Supporting fact 2"],
    "recommended_action": "Specific action to take"
  }}
]"""

        try:
            response = self.client.messages.create(
                model=config.model_standard,
                max_tokens=1000,
                system=system_prompt,
                messages=[{
                    "role": "user",
                    "content": f"Meeting segment to analyse:\n\n{text[-2000:]}"
                }],
                timeout=30,
            )

            raw = response.content[0].text.strip()
            # Strip markdown fences if present
            raw = re.sub(r"```json\s*|\s*```", "", raw).strip()

            data = json.loads(raw)
            challenges = []
            for item in data:
                if not isinstance(item, dict):
                    continue
                c = Challenge(
                    challenge_type=ChallengeType[
                        item.get("type", "DEVIL_ADVOCATE")
                    ],
                    urgency=ChallengeUrgency[
                        item.get("urgency", "DEFERRED")
                    ],
                    text=item.get("text", ""),
                    relevance_score=float(item.get("relevance_score", 0.5)),
                    trigger_statement=item.get("trigger_statement", ""),
                    evidence=item.get("evidence", []),
                    recommended_action=item.get("recommended_action", ""),
                )
                if c.text:
                    challenges.append(c)
            return challenges

        except (json.JSONDecodeError, KeyError, ValueError) as e:
            logger.warning(f"Challenge generation parse error: {e}")
            return []
        except Exception as e:
            logger.error(f"Challenge generation failed: {e}")
            return []

    def _extract_assumptions_llm(
        self,
        text: str,
        deal_context: DealContext,
    ) -> list[Challenge]:
        """Extract novel unstated assumptions using LLM analysis."""
        try:
            prompt = f"""Analyse this business conversation and identify unstated assumptions 
the team is making. Focus on assumptions that:
1. Are not explicitly stated but are implied by the decisions being made
2. If false, would materially change the decision
3. Could be tested or verified

Deal context: {deal_context.deal_name}, {deal_context.deal_type} deal, 
{deal_context.stage} stage with {deal_context.counterparty_name}.

Conversation:
{text[-1500:]}

Return JSON array of assumptions only (max 3). Each:
{{"assumption": "...", "consequence_if_false": "...", "how_to_verify": "..."}}

Return [] if no material unstated assumptions found."""

            response = self.client.messages.create(
                model=config.model_standard,
                max_tokens=600,
                messages=[{"role": "user", "content": prompt}],
                timeout=20,
            )
            raw = re.sub(r"```json\s*|\s*```", "",
                         response.content[0].text.strip()).strip()
            items = json.loads(raw)
            challenges = []
            for item in items:
                if not isinstance(item, dict):
                    continue
                challenges.append(Challenge(
                    challenge_type=ChallengeType.ASSUMPTION,
                    urgency=ChallengeUrgency.DEFERRED,
                    text=f"Unstated assumption: {item.get('assumption', '')}",
                    relevance_score=0.72,
                    recommended_action=(
                        f"Verify: {item.get('how_to_verify', '')} | "
                        f"Risk if false: {item.get('consequence_if_false', '')}"
                    ),
                ))
            return challenges
        except Exception:
            return []

    def _check_dd_gaps(
        self, asked_questions: list[str], deal_type: str
    ) -> list[str]:
        """Return list of unanswered DD questions."""
        checklist = DD_CHECKLISTS.get(deal_type, [])
        asked_lower = " ".join(asked_questions).lower()
        return [
            q for q in checklist
            if not any(
                term in asked_lower
                for term in self._extract_key_terms(q)[:2]
            )
        ]

    def _extract_key_terms(self, text: str) -> list[str]:
        """Extract 2-4 key terms from a question or statement."""
        stop = {
            "the", "a", "an", "is", "are", "has", "have", "been", "this",
            "that", "what", "which", "where", "when", "who", "how", "been",
            "does", "do", "did", "will", "would", "could", "should", "any",
        }
        words = re.findall(r"\b[a-zA-Z]{4,}\b", text.lower())
        return [w for w in words if w not in stop][:4]
