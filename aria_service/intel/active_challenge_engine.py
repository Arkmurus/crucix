# =============================================================================
# ARIA v3.1 — Active Challenge Engine
# aria_service/intel/active_challenge_engine.py
#
# WHAT THIS SOLVES:
#   ARIA currently listens and logs. This module makes her interject.
#   When the team converges on a decision, ARIA surfaces counterarguments.
#   When a counterparty makes a claim, ARIA questions its consistency.
#   When an assumption goes unstated, ARIA names it.
#
# INTEGRATION POINTS:
#   → aria_zoom_service.py: feed live captions here
#   → email/WhatsApp ingest: feed inbound messages here
#   → deal pipeline: feed deal context here
#   → delivery: post challenges to Zoom chat / team DM / WhatsApp
#
# DESIGN PRINCIPLE:
#   The challenge must be specific to the conversation, not generic.
#   A generic "have you considered the risks?" is useless.
#   A specific "you haven't asked who the UBO of this entity is,
#   and the ORSR shows three directors who are all PEP-adjacent" is valuable.
#
# AUTONOMY TIER: Tier 1 — Auto-allowed (internal channels only, no external send)
# =============================================================================

