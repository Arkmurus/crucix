# =============================================================================
# CHALLENGE TYPES
# =============================================================================

class ChallengeType(Enum):
    DEVIL_ADVOCATE    = "DEVIL_ADVOCATE"     # Counterargument to consensus
    DD_GAP            = "DD_GAP"             # Missing due diligence question
    ASSUMPTION        = "ASSUMPTION"          # Unstated assumption surfaced
    CONTRADICTION     = "CONTRADICTION"       # Inconsistency with prior statement
    RISK_BLIND_SPOT   = "RISK_BLIND_SPOT"    # Risk the team hasn't named
    COMPLIANCE_FLAG   = "COMPLIANCE_FLAG"    # Regulatory or legal gap


class ChallengeUrgency(Enum):
    IMMEDIATE = "IMMEDIATE"  # Post to channel now
    DEFERRED  = "DEFERRED"   # Add to end-of-meeting summary
    WEEKLY    = "WEEKLY"     # Surface in weekly assumption audit


# =============================================================================
# DEAL CONTEXT — what ARIA knows about the current deal
# =============================================================================

@dataclass
class DealContext:
    """
    Everything ARIA knows about the deal being discussed.
    Passed in from the deal pipeline before the meeting starts.
    """
    deal_name: str = ""
    deal_type: str = ""       # broker | oem | end_user | g2g | unknown
    stage: str = ""           # qualification | due_diligence | negotiation | closing
    counterparty_name: str = ""
    counterparty_country: str = ""
    programme_value_usd: float = 0.0
    prior_claims: list[dict] = field(default_factory=list)
    open_dd_items: list[str] = field(default_factory=list)
    known_risks: list[str] = field(default_factory=list)
    last_meeting_summary: str = ""


# =============================================================================
# CHALLENGE OUTPUT
# =============================================================================

@dataclass
class Challenge:
    """A single challenge generated by ARIA."""
    challenge_type: ChallengeType
    urgency: ChallengeUrgency
    text: str                          # The challenge text for posting
    relevance_score: float = 0.0       # 0-1 — only post if > threshold
    trigger_statement: str = ""        # The statement that triggered this
    evidence: list[str] = field(default_factory=list)
    recommended_action: str = ""
    generated_at: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )

    def to_chat_message(self) -> str:
        """Format for Zoom chat or WhatsApp posting."""
        prefix = {
            ChallengeType.DEVIL_ADVOCATE: "[ARIA — DEVIL'S ADVOCATE]",
            ChallengeType.DD_GAP:         "[ARIA — DD GAP]",
            ChallengeType.ASSUMPTION:     "[ARIA — UNSTATED ASSUMPTION]",
            ChallengeType.CONTRADICTION:  "[ARIA — CONTRADICTION FLAGGED]",
            ChallengeType.RISK_BLIND_SPOT:"[ARIA — BLIND SPOT]",
            ChallengeType.COMPLIANCE_FLAG:"[ARIA — COMPLIANCE]",
        }.get(self.challenge_type, "[ARIA]")

        lines = [prefix, "", self.text]
        if self.recommended_action:
            lines += ["", f"→ {self.recommended_action}"]
        if self.evidence:
            lines += ["", "Evidence:"]
            for e in self.evidence[:2]:
                lines.append(f"  • {e}")
        return "\n".join(lines)


